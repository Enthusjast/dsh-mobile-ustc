/** Test-only fresh fixture input from the private cluster; no production login/configuration entrypoint. */
object RunNativeModelsProbe {
    @JvmStatic fun main(args: Array<String>): Unit = runBlocking {
        var phase = "fixture"
        var ownedClient: OkHttpClient? = null
        try {
            require(args.size == 1)
            val root = File(System.getenv("REMOTE_TEST_CLUSTER_ROOT") ?: error("fixture root required")).canonicalFile
            val input = File(args[0]).canonicalFile
            require(input.toPath().startsWith(root.toPath()) && input.length() <= JsonDocument.MAX_BYTES)
            val fixture = JsonDocument.parse(input.readBytes()).root
            phase = "configuration"
            val config = LoginConfiguration.parse(JsonDocument.of(fixture.obj("deployment")).canonicalBytes())
            val key = ECKey.parse(JsonDocument.of(fixture.obj("proof_jwk")).canonicalText())
            val signer = object : DeviceProofSigner {
                override val publicKey = PublicProofKey(JsonDocument.parse(key.toPublicJWK().toJSONString()).root)
                override fun signJose(signingInput: ByteArray): ByteArray = ECDSASigner(key).sign(JWSHeader(JWSAlgorithm.ES256), signingInput).decode()
            }
            val now = System.currentTimeMillis()
            // The issuer, baseline and private key are generated by the Go test in this protected fixture directory.
            // Only the actual signed access JWT may authorize resource traffic after revalidation.
            val saved = jsonObject("v" to 1L.json(), "deployment_sha256" to config.fingerprint.json(), "issuer" to config.issuer.json(), "subject" to fixture.string("subject").json(),
                "client_id" to config.clientId.json(), "proof_key_jkt" to signer.publicKey.thumbprint.json(), "verified_at" to (now - 1000).json(),
                "access_expires_at" to fixture.integer("access_expires_at").json(), "scopes" to JsonArray(listOf("remote.access".json())),
                "access_token" to fixture.string("access_token").json(), "refresh_token" to JsonNull,
                "identity" to jsonObject("nonce" to "A".repeat(43).json(), "audiences" to JsonArray(listOf(config.clientId.json())), "azp" to JsonNull, "auth_time" to JsonNull))
            phase = "access-validation"
            val session = TokenVerifier.revalidateStored(StoredLogin.parseAuthenticated(JsonDocument.of(saved).canonicalBytes(), config, signer.publicKey.thumbprint, now), config,
                IssuerKeys.parse(JsonDocument.of(fixture.obj("issuer_jwks")).canonicalBytes()), now)
            phase = "tls-configuration"
            val certificate = CertificateFactory.getInstance("X.509").generateCertificate(fixture.string("ca_pem").byteInputStream()) as X509Certificate
            val trust = HandshakeCertificates.Builder().addTrustedCertificate(certificate).build()
            val fileTrust = fixture.fields["object_ca_pem"]?.let {
                val objectCertificate = CertificateFactory.getInstance("X.509").generateCertificate(fixture.string("object_ca_pem").byteInputStream()) as X509Certificate
                HandshakeCertificates.Builder().addTrustedCertificate(certificate).addTrustedCertificate(objectCertificate).build()
            } ?: trust
            val loseStatus = java.util.concurrent.atomic.AtomicBoolean(true)
            val lost = java.util.concurrent.atomic.AtomicInteger()
            val client = OkHttpClient.Builder().sslSocketFactory(fileTrust.sslSocketFactory(), fileTrust.trustManager)
                .addInterceptor { chain ->
                    val response = chain.proceed(chain.request())
                    if (chain.request().method == "GET" && chain.request().url.encodedPath.startsWith("/v1/commands/") && loseStatus.get()) {
                        response.close(); lost.incrementAndGet(); throw java.io.IOException("fixture response lost after real TLS response")
                    }
                    response
                }.build()
            ownedClient = client
            val http = LoginHttp.forTests(client)
            val api = http.resource(config, session, signer)
            phase = "native-models"
            val runtime = fixture.string("runtime_id"); val sid = fixture.string("session_id"); val device = fixture.string("device_id")
            val journal = MemoryCommandJournal(CommandOwner(UUID.randomUUID().toString(), config.organizationId, config.fingerprint, api.me().userId, device))
            val grant = RelayScope(listOf("session.read", "session.model.select", "message.submit", "command.status"), listOf(fixture.string("workspace_id")), emptyList())
            api.chatReader(device, runtime, sid, grant, journal, this, workspaceId = fixture.string("workspace_id")).use { reader ->
                withTimeout(20000) { reader.state.first { it.phase == SessionReadPhase.READY } }
                val models = reader.models
                withTimeout(5000) { models.state.first { it.phase == SessionModelCatalogPhase.IDLE } }
                check(models.loadInitial(1))
                var page = withTimeout(10000) { models.state.first { it.inFlight == 0 && it.items.isNotEmpty() } }
                check(page.items.size == 1 && page.hasMore && page.canSelect)
                val original = page.items.single()
                check(!models.loadInitial(1))
                var pages = 1
                while (page.hasMore) {
                    val count = page.items.size
                    check(models.loadNext(1))
                    page = withTimeout(10000) { models.state.first { it.inFlight == 0 && it.items.size > count } }
                    check(page.items.first() == original && page.items.size == count + 1)
                    check(++pages < 32)
                }
                val entries = page.items.filter { it.provider.id.startsWith("opaque/") }
                check(entries.size == 4)
                check(entries.map { it.provider.label }.distinct() == listOf("Duplicate provider"))
                check(entries.map { it.model.label }.distinct() == listOf("Duplicate model"))
                check(entries.map { it.provider.id to it.model.id }.distinct().size == 4)
                val selected = entries.last()
                check(selected.reasoningEfforts.map { it.id } == listOf("effort/low", "effort/high"))
                val commands = reader.commands!!
                val id = models.select(selected.provider.id, selected.model.id, "effort/high")
                withTimeout(10000) { while (lost.get() == 0) delay(25) }
                withTimeout(10000) { commands.state.first { it.records.any { row -> row.intent.requestId == id && row.attempts == 1L } } }
                check(journal.list(runtime, sid).single().intent.modelSelection() == SessionModelSelection(selected.provider.id, selected.model.id, "effort/high"))
                loseStatus.set(false)
                models.querySelection()
                val settled = withTimeout(15000) { commands.state.first { it.records.any { row -> row.intent.requestId == id && row.remote == RemoteCommandState.SETTLED } } }.records.single()
                check(settled.intent.requestId == id && settled.attempts == 1L && settled.everHostSaved)
                commands.sendPending(id)
                delay(250)
                check(journal.list(runtime, sid).single().attempts == 1L)
                val message = commands.submit("queue", "NATIVE_MODELS_EFFECTIVE_SELECTION")
                withTimeout(15000) { commands.state.first { it.records.any { row -> row.intent.requestId == message && row.everAgentQueued } } }
                withTimeout(15000) { reader.state.first { it.window?.items?.any { item -> item.blocks.any { block -> block.text == "Native selected offline response" } } == true } }
                File(fixture.string("ready_file")).writeText("confirmed")
                withTimeout(10000) { while (!File(fixture.string("retired_file")).exists()) delay(25) }
                withTimeout(10000) { models.state.first { !it.canSelect } }
                check(runCatching { models.select(selected.provider.id, selected.model.id, "effort/high") }.isFailure)
                check(journal.list(runtime, sid).count { it.intent.kind == CommandKind.MODEL_SELECT } == 1)
                println("PASS actual Kotlin models: limit=1 pages=$pages duplicate labels opaque identities effort/high; actual TLS status response loss=${lost.get()}; same original settled once; retired reader rejects selection")
            }
        } catch (error: Exception) {
            throw IllegalStateException("Native model probe failed at $phase", error)
        } finally { ownedClient?.let { it.connectionPool.evictAll(); it.dispatcher.executorService.shutdownNow() } }
    }
}
