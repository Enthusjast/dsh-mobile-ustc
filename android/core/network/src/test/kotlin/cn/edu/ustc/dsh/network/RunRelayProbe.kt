/** Test-only fresh fixture input from the private cluster; no production login/configuration entrypoint. */
object RunRelayProbe {
    @JvmStatic fun main(args: Array<String>): Unit = runBlocking {
        var phase = "fixture"
        var ownedClient: OkHttpClient? = null
        try {
            require(args.size == 1)
            val root = File(System.getenv("REMOTE_TEST_CLUSTER_ROOT") ?: error("fixture root required")).canonicalFile
            val input = File(args[0]).canonicalFile
            require(input.toPath().startsWith(root.toPath()) && input.length() <= JsonDocument.MAX_BYTES)
            val fixture = JsonDocument.parse(input.readBytes()).root
            phase = "configuration"
            val config = LoginConfiguration.parse(JsonDocument.of(fixture.obj("deployment")).canonicalBytes())
            val key = ECKey.parse(JsonDocument.of(fixture.obj("proof_jwk")).canonicalText())
            val signer = object : DeviceProofSigner {
                override val publicKey = PublicProofKey(JsonDocument.parse(key.toPublicJWK().toJSONString()).root)
                override fun signJose(signingInput: ByteArray): ByteArray = ECDSASigner(key).sign(JWSHeader(JWSAlgorithm.ES256), signingInput).decode()
            }
            val now = System.currentTimeMillis()
            // The issuer, baseline and private key are generated by the Go test in this protected fixture directory.
            // Only the actual signed access JWT may authorize resource traffic after revalidation.
            val saved = jsonObject("v" to 1L.json(), "deployment_sha256" to config.fingerprint.json(), "issuer" to config.issuer.json(), "subject" to fixture.string("subject").json(),
                "client_id" to config.clientId.json(), "proof_key_jkt" to signer.publicKey.thumbprint.json(), "verified_at" to (now - 1000).json(),
                "access_expires_at" to fixture.integer("access_expires_at").json(), "scopes" to JsonArray(listOf("remote.access".json())),
                "access_token" to fixture.string("access_token").json(), "refresh_token" to JsonNull,
                "identity" to jsonObject("nonce" to "A".repeat(43).json(), "audiences" to JsonArray(listOf(config.clientId.json())), "azp" to JsonNull, "auth_time" to JsonNull))
            phase = "access-validation"
            val session = TokenVerifier.revalidateStored(StoredLogin.parseAuthenticated(JsonDocument.of(saved).canonicalBytes(), config, signer.publicKey.thumbprint, now), config,
                IssuerKeys.parse(JsonDocument.of(fixture.obj("issuer_jwks")).canonicalBytes()), now)
            phase = "tls-configuration"
            val certificate = CertificateFactory.getInstance("X.509").generateCertificate(fixture.string("ca_pem").byteInputStream()) as X509Certificate
            val trust = HandshakeCertificates.Builder().addTrustedCertificate(certificate).build()
            val client = OkHttpClient.Builder().sslSocketFactory(trust.sslSocketFactory(), trust.trustManager).build()
            ownedClient = client
            val http = LoginHttp.forTests(client)
            val api = http.resource(config, session, signer)
            if (fixture.fields["mode"] == "binding".json()) {
                phase = "host-binding"
                binding(api, fixture, this)
                println("Kotlin HTTPS binding preview / reviewed confirmation / independent host-key confirmation / current directory grant passed")
                return@runBlocking
            }
            if (fixture.fields["mode"] == "content".json()) {
                phase = "session-content"
                content(api, fixture, root, this)
                println("Kotlin reader / TLS Go Relay / npm DSH: large Unicode snapshot, fixed history, live settlement and fresh-snapshot reopen passed")
                return@runBlocking
            }
            phase = "ticket"
            val ticket = api.readTicket(fixture.string("runtime_id"), fixture.string("device_id"), RelayScope(listOf("session.read"), emptyList(), listOf(fixture.string("session_id"))))
            phase = "handshake"
            withTimeout(15_000) { ticket.connect() }.use { connection ->
                require(connection.identity.deviceId == fixture.string("device_id"))
                require(connection.identity.runtimeId == fixture.string("runtime_id"))
                phase = "cache-read-authority"
                val until = api.cachedReadUntil(ticket.runtimeId, fixture.string("session_id"), fixture.string("workspace_id"), connection.identity.grantVersion)
                require(until > System.currentTimeMillis() && until <= System.currentTimeMillis() + 300_000)
                phase = "heartbeat"
                connection.send(jsonObject("v" to 1L.json(), "type" to "ping".json(), "payload" to jsonObject()))
                val pong = withTimeout(5000) { connection.receive() }
                require(pong.string("type") == "pong" && pong.obj("payload").string("connection_id") == connection.identity.connectionId)
                phase = "scoped-read"
                val request = UUID.randomUUID().toString()
                connection.send(jsonObject("v" to 1L.json(), "type" to "session.subscribe".json(), "request_id" to request.json(), "runtime_id" to ticket.runtimeId.json(),
                    "session_id" to fixture.string("session_id").json(), "payload" to jsonObject("max_messages" to 30L.json())))
                val offline = withTimeout(5000) { connection.receive() }
                require(offline.string("type") == "error" && offline.string("request_id") == request && offline.obj("payload").string("code") == "runtime.offline")
            }
            println("Kotlin HTTPS ticket / TLS Relay proof / heartbeat / scoped offline read passed")
        } catch (error: Exception) {
            // Content checks only expose protocol phases/codes, never fixture key or token parsing.
            if (phase in setOf("session-content", "host-binding")) throw IllegalStateException("Kotlin Relay probe failed at $phase", error)
            throw IllegalStateException("Kotlin Relay probe failed at $phase")
        }
        finally { ownedClient?.let { it.connectionPool.evictAll(); it.dispatcher.executorService.shutdownNow() } }
    }

    private suspend fun binding(api: RemoteApi, fixture: JsonObject, owner: CoroutineScope) {
        require("host_private_jwk" !in fixture.fields && "host_credential" !in fixture.fields)
        api.hostBinding(owner).use { flow ->
            suspend fun await(phase: HostBindingPhase) = withTimeout(15_000) { flow.state.first {
                check(it.phase !in setOf(HostBindingPhase.ERROR, HostBindingPhase.UNKNOWN, HostBindingPhase.UNAVAILABLE)) { "binding ${it.phase}: ${it.error}" }
                it.phase == phase
            } }
            flow.foreground(true); flow.preview(fixture.string("binding_id"), fixture.string("binding_code"))
            val review = await(HostBindingPhase.REVIEW)
            check(review.details!!.keyThumbprint == fixture.string("binding_key_jkt") && !review.details.confirmedByMe)
            check(!review.toString().contains(fixture.string("binding_code")))
            flow.confirm()
            val accepted = await(HostBindingPhase.READY).details!!
            check(accepted.confirmedByMe && accepted.hostConfirmed && accepted.state == "approved")
            check(accepted.runtimeId == fixture.string("binding_runtime_id"))
        }
    }

    private suspend fun content(api: RemoteApi, fixture: JsonObject, root: File, owner: CoroutineScope) {
        require("host_private_jwk" !in fixture.fields && "host_credential" !in fixture.fields)
        val runtime = fixture.string("runtime_id"); val session = fixture.string("session_id")
        val runtimeAccess = api.runtimes().obj("data").array("items").map { RuntimeDirectoryEntry.parse(it as JsonObject) }.single { it.id == runtime }
        val entry = withTimeout(5000) {
            var found: SessionDirectoryEntry? = null
            while (found == null) {
                found = api.sessions(runtime).obj("data").array("items").map { SessionDirectoryEntry.parse(it as JsonObject) }.firstOrNull { it.id == session }
                if (found == null) delay(50)
            }
            found
        }
        val scope = entry.readScope(runtimeAccess) ?: error("directory did not authorize the fixture read")
        check(scope.same(RelayScope(listOf("session.read"), listOf(fixture.string("workspace_id")), emptyList())))
        check(api.cachedReadUntil(runtime, session, entry.workspaceId, runtimeAccess.grantVersion!!) > System.currentTimeMillis())
        var settledCursor = -1L
        api.reader(fixture.string("device_id"), runtime, session, scope, owner).use { reader ->
            suspend fun await(test: (SessionReadState) -> Boolean) = withTimeout(20_000) { reader.state.first { state ->
                check(state.phase !in setOf(SessionReadPhase.ERROR, SessionReadPhase.REVOKED, SessionReadPhase.AUTH_REQUIRED)) { state.error ?: "reader stopped" }
                test(state)
            } }
            val opening = await { it.phase == SessionReadPhase.READY && it.window?.checkpoint == "persisted" }
            val cut = opening.window!!.openingCursor
            check(opening.window.hasMore)
            check(opening.window.items.sumOf { item -> item.blocks.sumOf { it.text.length } } > JsonDocument.MAX_BYTES)
            while (reader.state.value.window!!.hasMore) {
                val count = reader.state.value.window!!.records.size
                reader.loadOlder()
                await { !it.loadingOlder && (it.window?.records?.size ?: 0) > count }
            }
            val history = reader.state.value.window!!
            check(history.openingCursor == cut && history.cursor == cut)
            check(history.items.count { it.role == cn.edu.ustc.dsh.session.ConversationRole.USER } == 16) {
                "native history roles=${history.items.groupingBy { it.role }.eachCount()}, events=${history.records.groupingBy { it.type }.eachCount()}, fixture_prompts=${history.items.count { it.blocks.any { block -> block.text.startsWith("KOTLIN_HISTORY_") } }}"
            }
            check(history.items.count { it.role == cn.edu.ustc.dsh.session.ConversationRole.ASSISTANT } == 16)
            check(history.items.any { it.blocks.any { block -> block.text.startsWith("KOTLIN_HISTORY_0 ") && block.text.contains("中🙂") } })
            val ready = File(fixture.string("ready_file")).canonicalFile
            require(ready.toPath().startsWith(root.toPath()))
            ready.writeText("ready")
            val live = await { it.window?.let { window -> window.cursor > cut && window.persistedThrough >= window.cursor && !window.taskRunning &&
                window.items.none { item -> item.live } && window.items.any { item -> item.blocks.any { block -> block.text == "KOTLIN_LIVE_MARKER" } } &&
                window.items.count { item -> item.role == cn.edu.ustc.dsh.session.ConversationRole.ASSISTANT } == 17 } == true }
            check(live.window!!.items.map { it.id }.toSet().size == live.window.items.size)
            settledCursor = live.window.cursor
        }
        api.reader(fixture.string("device_id"), runtime, session, scope, owner).use { reopened ->
            val snapshot = withTimeout(10_000) { reopened.state.first { it.phase == SessionReadPhase.READY && it.window?.checkpoint == "persisted" } }.window!!
            check(snapshot.cursor >= settledCursor && snapshot.items.none { it.live })
            check(snapshot.items.last().blocks.single().text == "DSH local integration fixture response")
        }
        val account = api.me()
        val config = LoginConfiguration.parse(JsonDocument.of(fixture.obj("deployment")).canonicalBytes())
        val journal = MemoryCommandJournal(CommandOwner(UUID.randomUUID().toString(), config.organizationId, config.fingerprint, account.userId, fixture.string("device_id")))
        val commandScope = runtimeAccess.scope!!.session(session, entry.workspaceId, setOf("session.read", "message.submit", "command.status", "session.cancel"))
        api.chatReader(fixture.string("device_id"), runtime, session, commandScope, journal, owner).use { chat ->
            withTimeout(10_000) { chat.state.first { it.phase == SessionReadPhase.READY } }
            val writer = chat.commands!!
            val id = writer.submit("queue", "KOTLIN_SOCKET_SEND")
            withTimeout(15_000) { writer.state.first { it.records.any { command -> command.intent.requestId == id && command.everAgentQueued } } }
            val observed = withTimeout(15_000) { chat.state.first { it.window?.items?.any { item -> item.blocks.any { block -> block.text == "KOTLIN_SOCKET_SEND" } } == true } }
            val nativeCursor = observed.window!!.cursor
            writer.sendPending(id) // Same-ID explicit action queries first; queued intent cannot be replayed.
            withTimeout(5000) { writer.state.first { it.error == "command.reconcile_required" } }
            check(journal.list(runtime, session).single().attempts == 1L)
            check(chat.state.value.window!!.cursor >= nativeCursor)
            writer.submit("queue", "REMOTE_CANCEL_WAIT")
            val waiting = withTimeout(15_000) { chat.state.first { it.window?.items?.any { item -> item.live && item.blocks.any { block -> block.text.contains("Cancelable model call is waiting") } } == true } }
            val cancellation = writer.cancel(waiting.runtimeEpoch!!)
            withTimeout(10_000) { writer.state.first { it.records.any { command -> command.intent.requestId == cancellation && command.remote == RemoteCommandState.SETTLED } } }
            withTimeout(10_000) { chat.state.first { it.window?.let { window -> !window.taskRunning && window.items.any { item -> item.interrupted } } == true } }
        }
        val workspace=entry.workspaceId ?: error("registered creation workspace required")
        val creationScope=RelayScope(listOf("session.create","command.status"),listOf(workspace),emptyList())
        var created: String?=null
        api.sessionCreator(fixture.string("device_id"),runtime,creationScope,journal,owner).use { flow ->
            val options=withTimeout(10_000) {flow.state.first {it.phase==SessionCreationPhase.READY}}.options!!
            check(options.workspaces.any {it.id==workspace} && "standard" in options.presets)
            val request=flow.create(workspace,"standard",options.epoch)
            val record=withTimeout(15_000) {flow.state.first {it.outbox.records.any {row->row.intent.requestId==request && row.createdSessionId!=null}}}.outbox.records.single {it.intent.requestId==request}
            check(record.intent.sessionId==null && record.intent.workspaceId==workspace && record.attempts==1L)
            created=record.createdSessionId
            flow.sendPending(request)
            withTimeout(5000) {flow.state.first {it.outbox.error=="command.reconcile_required"}}
            check(journal.listCreations(runtime).single().attempts==1L)
        }
        val result=api.sessions(runtime).obj("data").array("items").map {SessionDirectoryEntry.parse(it as JsonObject)}.single {it.id==created}
        val createdScope=runtimeAccess.scope!!.session(result.id,result.workspaceId,setOf("session.read","message.submit","question.answer","command.status"))
        api.chatReader(fixture.string("device_id"),runtime,result.id,createdScope,journal,owner).use {reader->
            withTimeout(10_000) {reader.state.first {it.phase==SessionReadPhase.READY}}
            val writer=reader.commands!!
            val request=writer.submit("queue","KOTLIN_CREATED_SESSION_CONTINUE")
            withTimeout(15_000) {writer.state.first {it.records.any {row->row.intent.requestId==request && row.everAgentQueued}}}
            val completed=withTimeout(15_000) {reader.state.first {it.window?.items?.any {item->item.role==cn.edu.ustc.dsh.session.ConversationRole.ASSISTANT && item.persisted && item.blocks.any {block->block.text=="DSH local integration fixture response"}}==true}}
            check(completed.window!!.items.count {item->item.blocks.any {block->block.text=="KOTLIN_CREATED_SESSION_CONTINUE"}}==1)
            writer.submit("queue","M0_QUESTION_TEST_KOTLIN")
            val pending=withTimeout(10_000) {reader.state.first {it.questions.items.any {item->item.batch.kind==QuestionKind.BLOCKING}}}.questions.items.single {it.batch.kind==QuestionKind.BLOCKING}
            val answer=reader.answerQuestion(pending.handle,QuestionAnswers(pending.batch.id,listOf(QuestionAnswer("m0-choice",listOf("Local answer"),"KOTLIN_BLOCKING_REPLY"))))
            val answered=withTimeout(10_000) {writer.state.first {it.records.any {row->row.intent.requestId==answer && row.remote==RemoteCommandState.SETTLED}}}.records.single {it.intent.requestId==answer}
            check(!answered.everAgentQueued && answered.intent.questionDefinition==pending.batch.definition)
            withTimeout(10_000) {reader.state.first {it.questions.items.none {item->item.batch.id==pending.batch.id} && it.window?.taskRunning==false}}
        }
        var timedSession: String?=null
        api.sessionCreator(fixture.string("device_id"),runtime,creationScope,journal,owner).use {flow->
            val options=withTimeout(10_000) {flow.state.first {it.phase==SessionCreationPhase.READY}}.options!!
            check("remote-timed" in options.presets)
            val request=flow.create(workspace,"remote-timed",options.epoch)
            timedSession=withTimeout(10_000) {flow.state.first {it.outbox.records.any {row->row.intent.requestId==request && row.createdSessionId!=null}}}.outbox.records.single {it.intent.requestId==request}.createdSessionId
        }
        val timedScope=runtimeAccess.scope!!.session(timedSession!!,workspace,setOf("session.read","message.submit","question.answer","command.status"))
        api.chatReader(fixture.string("device_id"),runtime,timedSession!!,timedScope,journal,owner).use {reader->
            withTimeout(10_000) {reader.state.first {it.phase==SessionReadPhase.READY}}
            val writer=reader.commands!!
            writer.submit("queue","REMOTE_TIMED_FOREGROUND_KOTLIN")
            val first=withTimeout(10_000) {reader.state.first {it.questions.items.any {item->item.batch.kind==QuestionKind.TIMED && item.batch.phase==QuestionPhase.OPEN}}}.questions.items.first {it.batch.kind==QuestionKind.TIMED && it.batch.phase==QuestionPhase.OPEN}
            reader.claimQuestion(first.handle)
            val claimed=withTimeout(5000) {reader.state.first {it.questions.items.any {item->item.batch.id==first.batch.id && item.claim?.phase==ClaimPhase.ACTIVE}}}.questions.items.single {it.batch.id==first.batch.id}
            check(claimed.remainingMillis!=null && claimed.remainingMillis!!<=10_000)
            val foreground=reader.answerQuestion(claimed.handle,QuestionAnswers(claimed.batch.id,listOf(QuestionAnswer("timed-choice",listOf("Reply"),"KOTLIN_TIMED_FOREGROUND_REPLY"))))
            val consumed=withTimeout(10_000) {writer.state.first {it.records.any {row->row.intent.requestId==foreground && row.remote==RemoteCommandState.SETTLED}}}.records.single {it.intent.requestId==foreground}
            check(!consumed.everAgentQueued)
            withTimeout(10_000) {reader.state.first {it.questions.items.none {item->item.batch.id==first.batch.id} && it.window?.taskRunning==false}}
            writer.submit("queue","REMOTE_TIMED_RELEASE_KOTLIN")
            val second=withTimeout(10_000) {reader.state.first {it.questions.items.any {item->item.batch.kind==QuestionKind.TIMED && item.batch.phase==QuestionPhase.OPEN}}}.questions.items.first {it.batch.kind==QuestionKind.TIMED && it.batch.phase==QuestionPhase.OPEN}
            reader.claimQuestion(second.handle)
            withTimeout(5000) {reader.state.first {it.questions.items.any {item->item.batch.id==second.batch.id && item.claim?.phase==ClaimPhase.ACTIVE}}}
            reader.releaseQuestion(second.handle)
            val continued=withTimeout(10_000) {reader.state.first {it.questions.items.any {item->item.batch.id==second.batch.id && item.batch.phase==QuestionPhase.CONTINUED}}}.questions.items.single {it.batch.id==second.batch.id}
            val late=reader.answerQuestion(continued.handle,QuestionAnswers(continued.batch.id,listOf(QuestionAnswer("timed-choice",listOf("Reply"),"KOTLIN_TIMED_LATE_REPLY"))))
            withTimeout(10_000) {writer.state.first {it.records.any {row->row.intent.requestId==late && row.everAgentQueued}}}
            withTimeout(10_000) {reader.state.first {it.window?.items?.any {item->item.blocks.any {block->block.text.contains("KOTLIN_TIMED_LATE_REPLY")}}==true}}
        }
    }
}
