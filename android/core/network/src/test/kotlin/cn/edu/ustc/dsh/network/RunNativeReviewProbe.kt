/** Test-only fresh fixture input from the private cluster; no production login/configuration entrypoint. */
object RunNativeReviewProbe {
    @JvmStatic fun main(args: Array<String>): Unit = runBlocking {
        var phase = "fixture"
        var ownedClient: OkHttpClient? = null
        try {
            require(args.size == 1)
            val root = File(System.getenv("REMOTE_TEST_CLUSTER_ROOT") ?: error("fixture root required")).canonicalFile
            val input = File(args[0]).canonicalFile
            require(input.toPath().startsWith(root.toPath()) && input.length() <= JsonDocument.MAX_BYTES)
            val fixture = JsonDocument.parse(input.readBytes()).root
            phase = "configuration"
            val config = LoginConfiguration.parse(JsonDocument.of(fixture.obj("deployment")).canonicalBytes())
            val key = ECKey.parse(JsonDocument.of(fixture.obj("proof_jwk")).canonicalText())
            val signer = object : DeviceProofSigner {
                override val publicKey = PublicProofKey(JsonDocument.parse(key.toPublicJWK().toJSONString()).root)
                override fun signJose(signingInput: ByteArray): ByteArray = ECDSASigner(key).sign(JWSHeader(JWSAlgorithm.ES256), signingInput).decode()
            }
            val now = System.currentTimeMillis()
            // The issuer, baseline and private key are generated by the Go test in this protected fixture directory.
            // Only the actual signed access JWT may authorize resource traffic after revalidation.
            val saved = jsonObject("v" to 1L.json(), "deployment_sha256" to config.fingerprint.json(), "issuer" to config.issuer.json(), "subject" to fixture.string("subject").json(),
                "client_id" to config.clientId.json(), "proof_key_jkt" to signer.publicKey.thumbprint.json(), "verified_at" to (now - 1000).json(),
                "access_expires_at" to fixture.integer("access_expires_at").json(), "scopes" to JsonArray(listOf("remote.access".json())),
                "access_token" to fixture.string("access_token").json(), "refresh_token" to JsonNull,
                "identity" to jsonObject("nonce" to "A".repeat(43).json(), "audiences" to JsonArray(listOf(config.clientId.json())), "azp" to JsonNull, "auth_time" to JsonNull))
            phase = "access-validation"
            val session = TokenVerifier.revalidateStored(StoredLogin.parseAuthenticated(JsonDocument.of(saved).canonicalBytes(), config, signer.publicKey.thumbprint, now), config,
                IssuerKeys.parse(JsonDocument.of(fixture.obj("issuer_jwks")).canonicalBytes()), now)
            phase = "tls-configuration"
            val certificate = CertificateFactory.getInstance("X.509").generateCertificate(fixture.string("ca_pem").byteInputStream()) as X509Certificate
            val trust = HandshakeCertificates.Builder().addTrustedCertificate(certificate).build()
            val fileTrust = fixture.fields["object_ca_pem"]?.let {
                val objectCertificate = CertificateFactory.getInstance("X.509").generateCertificate(fixture.string("object_ca_pem").byteInputStream()) as X509Certificate
                HandshakeCertificates.Builder().addTrustedCertificate(certificate).addTrustedCertificate(objectCertificate).build()
            } ?: trust
            val client = OkHttpClient.Builder().sslSocketFactory(fileTrust.sslSocketFactory(), fileTrust.trustManager).build()
            ownedClient = client
            val http = LoginHttp.forTests(client)
            val api = http.resource(config, session, signer)
            phase = "native-review"
            review(api, fixture, root, config, this)
        } catch (error: Exception) {
            throw IllegalStateException("Kotlin native review failed at $phase", error)
        } finally { ownedClient?.let { it.connectionPool.evictAll(); it.dispatcher.executorService.shutdownNow() } }
    }

    private suspend fun review(api: RemoteApi, fixture: JsonObject, root: File, config: LoginConfiguration, owner: CoroutineScope) {
        require(fixture.fields.keys.none { it.startsWith("host_") })
        val runtime = fixture.string("runtime_id"); val session = fixture.string("session_id")
        val workspace = fixture.string("workspace_id"); val device = fixture.string("device_id")
        val account = api.me()
        val journal = MemoryCommandJournal(CommandOwner(UUID.randomUUID().toString(), config.organizationId, config.fingerprint, account.userId, device))
        val scope = RelayScope(listOf("session.read", "session.changes.read", "session.fork", "session.create", "command.status"), listOf(workspace), emptyList())
        fun marker(name: String) {
            val file = File(fixture.string(name)).canonicalFile
            require(file.toPath().startsWith(root.toPath()))
            file.writeText("ready")
        }
        api.chatReader(device, runtime, session, scope, journal, owner, workspaceId = workspace).use { reader ->
            suspend fun ready() = withTimeout(20_000) { reader.state.first {
                check(it.phase !in setOf(SessionReadPhase.ERROR, SessionReadPhase.REVOKED, SessionReadPhase.AUTH_REQUIRED)) { "reader ${it.phase}: ${it.error}" }
                it.phase == SessionReadPhase.READY && it.window?.checkpoint == "persisted"
            } }
            suspend fun changes() = withTimeout(15_000) { reader.changes.state.first {
                check(it.phase !in setOf(SessionChangesPhase.ERROR, SessionChangesPhase.DENIED, SessionChangesPhase.UNAVAILABLE, SessionChangesPhase.STALE)) { "changes ${it.phase}: ${it.error}" }
                !it.loading && it.phase == SessionChangesPhase.READY
            } }
            suspend fun preview(): SessionMessagePreview {
                val item = reader.state.value.window!!.items.single { item -> item.role == cn.edu.ustc.dsh.session.ConversationRole.USER && item.persisted && !item.live && item.blocks.any { it.text == "KOTLIN_REVIEW_HUMAN" } }
                check(reader.messageActions.previewMessage(item.id))
                return withTimeout(10_000) { reader.messageActions.state.first {
                    check(it.phase !in setOf(SessionMessageActionPhase.ERROR, SessionMessageActionPhase.STALE, SessionMessageActionPhase.DENIED)) { "preview ${it.phase}: ${it.error}" }
                    it.phase == SessionMessageActionPhase.READY
                } }.preview!!
            }
            ready()
            withTimeout(5000) { reader.changes.state.first { it.phase == SessionChangesPhase.IDLE } }
            check(reader.changes.loadInitial(2)); changes()
            while (reader.changes.state.value.hasMore) { check(reader.changes.loadNext(2)); changes() }
            val snapshot = reader.changes.state.value
            check(snapshot.manifest!!.baseOid == fixture.string("git_base"))
            check(snapshot.manifest.version == fixture.string("git_version"))
            check(snapshot.files.size == fixture.array("expected_patches").size)
            check(snapshot.files.map { it.status }.containsAll(listOf("added", "deleted", "renamed", "modified")))
            var partialObserved = false
            for (expectedValue in fixture.array("expected_patches")) {
                val expected = expectedValue as JsonObject
                val file = snapshot.files.single { (it.newPath ?: it.oldPath)!!.display == expected.string("path") }
                check(reader.changes.loadPatch(file.fileId)); changes()
                while (reader.changes.state.value.patchHasMore) {
                    check(reader.changes.completePatch() == null)
                    check(reader.changes.state.value.patch!!.partial)
                    partialObserved = true
                    check(reader.changes.loadNextPatch()); changes()
                }
                if (file.kind == "binary") {
                    check(!file.complete && reader.changes.completePatch() == null)
                } else {
                    val actual = reader.changes.completePatch() ?: error("complete patch missing")
                    val expectedBytes = java.util.Base64.getDecoder().decode(expected.string("base64"))
                    check(actual.toByteArray(Charsets.UTF_8).contentEquals(expectedBytes)) { "complete patch bytes changed" }
                    check(reader.changes.state.value.canCopyComplete)
                }
            }
            check(partialObserved)
            val textFile = snapshot.files.single { (it.newPath ?: it.oldPath)!!.display == "review.txt" }
            check(reader.changes.loadPatch(textFile.fileId)); changes()
            while (reader.changes.state.value.patchHasMore) { check(reader.changes.loadNextPatch()); changes() }
            val first = preview()
            check(first.text == "KOTLIN_REVIEW_HUMAN" && first.shareable)
            check(first.anchor.nativeSeq == fixture.integer("human_seq"))
            val staleShare = reader.messageActions.confirmShare(first.anchor)
            check(staleShare.current() && staleShare.text == "KOTLIN_REVIEW_HUMAN")
            val oldSync = first.anchor.syncId
            reader.refreshQuestions()
            withTimeout(15_000) {
                while (staleShare.current() || reader.changes.completePatch() != null) delay(25)
            }
            ready()
            withTimeout(5000) { reader.changes.state.first { it.phase == SessionChangesPhase.IDLE } }
            check(reader.changes.state.value.patch == null && reader.messageActions.state.value.preview == null)
            val fresh = preview()
            check(fresh.anchor.syncId != oldSync)
            check(runCatching { reader.messageActions.confirmShare(first.anchor) }.exceptionOrNull() is CommandDataException)
            val id = reader.messageActions.fork(fresh.anchor)
            val commands = reader.commands!!
            val settled = withTimeout(20_000) { commands.state.first { state -> state.records.any { it.intent.requestId == id && it.remote == RemoteCommandState.SETTLED } } }.records.single { it.intent.requestId == id }
            check(settled.createdSessionId != null && settled.createdSessionId != session)
            check(settled.forkOutcome?.checkpoint == "persisted" && settled.forkOutcome?.workspaceAttachment == "attached")
            check(!reader.messageActions.state.value.canFork && reader.messageActions.state.value.originalRequestId == id)
            check(runCatching { reader.messageActions.fork(fresh.anchor) }.exceptionOrNull() is CommandDataException)
            reader.messageActions.queryFork(id)
            commands.sendPending(id)
            delay(200)
            check(api.commandStatus(id, device).state == RemoteCommandState.SETTLED)
            val current = preview()
            val share = reader.messageActions.confirmShare(current.anchor)
            check(share.current() && share.text == "KOTLIN_REVIEW_HUMAN")
            check(reader.changes.loadInitial()); changes()
            val finalFile = reader.changes.state.value.files.single { (it.newPath ?: it.oldPath)!!.display == "review.txt" }
            check(reader.changes.loadPatch(finalFile.fileId)); changes()
            while (reader.changes.state.value.patchHasMore) { check(reader.changes.loadNextPatch()); changes() }
            check(reader.changes.completePatch() != null)
            marker("revoke_marker")
            withTimeout(15_000) { reader.state.first { it.phase == SessionReadPhase.REVOKED } }
            check(!share.current() && !staleShare.current())
            check(reader.changes.completePatch() == null && reader.changes.state.value.patch == null && reader.changes.state.value.manifest == null)
            check(reader.messageActions.state.value.preview == null && !reader.messageActions.canPreview)
            println("kotlin_review_consumer exact_git_patch=true paged_partial_not_copyable=true binary_not_copyable=true base_and_version=true visible_persisted_human=true preview_confirm=true native_fork_settled=true child_checkpoint=persisted original_query_no_refork=true stale_sync_clears=true revoked_share_current=false revoked_patch_closed=true desktop_share=false")
        }
    }
}
